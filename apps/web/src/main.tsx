import React from 'react';
import { createRoot } from 'react-dom/client';
import { BrowserRouter } from 'react-router-dom';
import { QueryClient, QueryClientProvider } from '@tanstack/react-query';
import { DAppKitProvider, createDAppKit } from '@mysten/dapp-kit-react';
import { SuiGrpcClient } from '@mysten/sui/grpc';
import { App } from './app.js';
import './styles.css';
export const queryClient=new QueryClient({defaultOptions:{queries:{retry:false,refetchOnWindowFocus:false},mutations:{retry:false}}});
const dAppKit=createDAppKit({networks:['mainnet'],createClient:()=>new SuiGrpcClient({network:'mainnet',baseUrl:'https://fullnode.mainnet.sui.io:443'}),slushWalletConfig:null});
createRoot(document.getElementById('root')!).render(<React.StrictMode><QueryClientProvider client={queryClient}><DAppKitProvider dAppKit={dAppKit}><BrowserRouter><App/></BrowserRouter></DAppKitProvider></QueryClientProvider></React.StrictMode>);
